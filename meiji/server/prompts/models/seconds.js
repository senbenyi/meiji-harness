const handoffRules = "end_state 写最后一刻的位置、朝向、姿态、服装、持物和关键物件，不得为空。pending_actions 只记尚未完成的身体动作，不代写待续台词；pending_dialogue 只记有明确依据、尚未说出且需要跨镜继续的原话。被他人打断、主动停住或本镜原话已呈现完时，没有明确后续原话就留空，不因破折号或省略号认定需要续说。continuing_audio 只记切点仍在的声音。没有就留空。顶层这四项必须和最后一拍一致。";
const beatRules = "从 0 秒连续覆盖到参考时长，末段结束等于参考时长，段与段不留空、不重叠。一拍一个主要动作或一段持续状态。剪辑切镜或需要独立呈现的说话人切换才开新拍，其他时点写在拍内。普通短动作允许亚秒节拍，持续状态可跨多秒。不用一整拍盖过镜内多个事件，也不把一个连续动作拆成重复拍。先排完原台词和动作再分配时长。串行分开计时，并行写明关系。不靠新剧情、重复或空等填时间。time_range 只是这一拍的起止，不是视频切镜，也不写 [Shot]。机位未变时 camera 写明机位未变；只有真正换机位才在 camera 写明剪辑切镜和新机位。跨秒停留在 action 写明保持什么、大约多久。";
