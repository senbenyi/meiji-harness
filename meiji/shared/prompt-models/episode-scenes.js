// 生成、修订、审核都用短规则。审核分类由 reviewPolicy 统一追加。
const coreRules = "只收录反复出现、对剧情或空间连续重要、或用户明确要求固定的地点。一次性、不重要地点不建资料、不要求参考图。没有符合条件的地点返回空数组。同一段拆成多个镜头不算反复出现。不要把全部地点列成清单。只返回本集实际使用且符合条件的地点。相同地点复用已有 id，新增 id 为空；本集没出现的旧场景不返回。房间角落、远近景、正反打、昼夜、天气或光照变化不另建场景。已有场景返回原 id 与名称，其余字段照抄，程序以项目资料为准。新地点才写 description、layout、materials、lighting，不增加剧情、人物或关键物件。先合并重复地点再输出。";
const granularityRules = "一个场景是同一总体布局能表达的拍摄地点，不是每个机位。同一连续室外场地可以包含多个分区，用总体布局说明相对关系，不因栅门内外、远近或站位拆分。只有原文明确是不同建筑、室内与室外彼此封闭，或固定布局无法共存，且各自符合收录条件时才拆分。一过性外围区域可以只留正文。";
const reviewRules = "核对收录、复用和重复。语义相同即通过，不能声称不符又要求改回候选已经写出的内容。拒绝须给出互相冲突的两项事实或明确遗漏，以及最小修正。有窗写窗光、有灯写灯光可以通过；夜晚开灯属于镜头状态，不因此删除基础窗光。合理的空间风格归纳可以通过。指出具体重复项和合并目标。一次性不重要地点未收录是正确的，不因空结果或没有参考图拒绝。已有总体布局时不要求拆开。前轮要求合并且修订已落实、没有新的空间事实时，不得改口要求重新拆分。";
const stage = (action, task) => ({
  system: {
    规则: {
      场景统一: coreRules,
      场景粒度: granularityRules,
      ...(action === 'review' ? { 核对清单: reviewRules } : { 输出: "返回本集符合收录条件的场景。保留已有 ID，不删除其他剧集的地点。" }),
      ...(action === 'regenerate' ? { 修改范围: "返回完整场景数组。只改意见点到的地点，优先合并重复地点。没点到的已有场景保持 ID 和资料不变。" } : {}),
    },
  },
  user: {
    任务: task,
    背景信息: { 分集改编: "{{分集改编}}", 已有场景: "{{已有场景}}", 剧情上下文: "{{剧情上下文}}" },
    ...(action === 'generate' ? {} : action === 'review' ? { 待审核内容: "{{待审核内容}}", 本次要求及此前审核意见: "{{修改意见}}" } : { 基稿: "{{基稿}}", 修改意见: "{{修改意见}}" }),
    补充需求: "{{补充需求}}",
  },
});
export default {
  generate: stage('generate', '提取并统一本集场景。'),
  regenerate: stage('regenerate', '按意见修订本集场景，优先合并重复地点。'),
  review: stage('review', '按核对清单审核场景收录和复用。通过时原因留空。'),
};
