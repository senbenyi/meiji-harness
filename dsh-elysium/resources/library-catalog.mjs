function digest(key) {
  return createHash('md5').update(`elysium-library:${key}`).digest('hex')
}

function promptOf(item, view) {
  const shot = (views[item.kind] || views.subject)[view]
  return `${prefixes[item.kind]}, ${item.identity}, ${shot}, same identity across turnaround views, plain studio or natural lighting matching the subject, no text, no collage, no watermark.`
}

