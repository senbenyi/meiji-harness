// 生成、修订、审核都用短规则。审核分类由 reviewPolicy 统一追加。
import { sceneCompletionRule } from './common.js';
const coreRules = "本集实际使用的拍摄地点，满足反复出现、对剧情或空间连续重要、用户明确要求固定任一条件即收录，不必同时满足。承载主要行动的大型固定设施及作业区域属于场景；仅被提及的物件和随身道具不因此建场景。一次性且不重要、无明确要求的地点不建资料、不要求参考图。逐段识别符合条件的地点，合并后均无才返回空数组。同一段拆成多个镜头不算反复出现，不把全部地点列成清单。相同地点复用已有 id，新增 id 为空；本集没出现的旧场景不返回。房间角落、远近景、正反打、昼夜、天气或光照变化不另建场景。已有场景保留原 id，资料是否可修正按本次已有场景维护范围执行。新地点及允许修正的场景填写 description、layout、materials、lighting，只记录静态环境、布局、材质与基础光源，不写人物出场、站位或动作，不增加剧情或关键物件。先合并重复地点再输出。";
const granularityRules = "一个场景是同一总体布局能表达的拍摄地点，不是每个机位。同一连续室外场地可以包含多个分区，用总体布局说明相对关系，不因栅门内外、远近或站位拆分。只有原文明确是不同建筑、室内与室外彼此封闭，或固定布局无法共存，且各自符合收录条件时才拆分。一过性外围区域可以只留正文。";
const reviewRules = "先独立对照本集分集改编核对符合收录条件的地点是否遗漏，再核对复用和重复。语义相同即通过，不能声称不符又要求改回候选已经写出的内容。拒绝须给出互相冲突的两项事实或明确遗漏，以及最小修正。有窗写窗光、有灯写灯光可以通过；夜晚开灯属于镜头状态，不因此删除基础窗光。合理的空间风格归纳可以通过。指出具体重复项和合并目标。空结果仅在本集确无符合条件的地点时通过；遗漏须指出改编中的地点及其满足的收录条件。一次性不重要地点未收录、没有参考图均不是拒绝理由。已有总体布局时不要求拆开。前轮要求合并且修订已落实、没有新的空间事实时，不得改口要求重新拆分。";
const stage = (action, task) => ({
  system: {
    规则: {
      场景统一: coreRules,
      场景补全: sceneCompletionRule,
      场景粒度: granularityRules,
      ...(action === 'review' ? { 核对清单: reviewRules } : { 输出: "返回本集符合收录条件的场景。保留已有 ID，不删除其他剧集的地点。" }),
      ...(action === 'regenerate' ? { 修改范围: "返回完整场景数组。只改意见点到的地点，优先合并重复地点。没点到的已有场景保持 ID 和资料不变。" } : {}),
    },
  },
  user: {
    任务: task,
    背景信息: { 分集改编: "{{分集改编}}", 已有场景: "{{已有场景}}", 剧情上下文: "{{剧情上下文}}", 已有场景维护范围: "{{已有场景维护范围}}" },
    ...(action === 'generate' ? {} : action === 'review' ? { 待审核内容: "{{待审核内容}}", 本次要求及此前审核意见: "{{修改意见}}" } : { 基稿: "{{基稿}}", 修改意见: "{{修改意见}}" }),
    补充需求: "{{补充需求}}",
  },
});
export default {
  generate: stage('generate', '提取并统一本集场景。'),
  regenerate: stage('regenerate', '按意见修订本集场景，优先合并重复地点。'),
  review: stage('review', '按核对清单审核场景收录和复用。通过时原因留空。'),
};
